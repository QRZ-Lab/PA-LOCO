import torch
import torch.nn as nn
import torch.optim as optim

from rsl_rl.modules import ActorCriticMlpEncoderResidual
from rsl_rl.storage import RolloutStorage
from .ppo import PPO


class PPOResidual(PPO):
    actor_critic: ActorCriticMlpEncoderResidual

    def __init__(self,
                 actor_critic,
                 num_learning_epochs=1,
                 num_mini_batches=1,
                 clip_param=0.2,
                 gamma=0.998,
                 lam=0.95,
                 value_loss_coef=1.0,
                 entropy_coef=0.0,
                 learning_rate=1e-3,
                 max_grad_norm=1.0,
                 use_clipped_value_loss=True,
                 schedule="fixed",
                 desired_kl=0.01,
                 device='cpu',
                 **kwargs):
        super().__init__(actor_critic,
                         num_learning_epochs=num_learning_epochs,
                         num_mini_batches=num_mini_batches,
                         clip_param=clip_param,
                         gamma=gamma,
                         lam=lam,
                         value_loss_coef=value_loss_coef,
                         entropy_coef=entropy_coef,
                         learning_rate=learning_rate,
                         max_grad_norm=max_grad_norm,
                         use_clipped_value_loss=use_clipped_value_loss,
                         schedule=schedule,
                         desired_kl=desired_kl,
                         device=device,
                         **kwargs)

    def act(self, obs, critic_obs):
        """ 根据当前状态生成动作，同时记录状态，动作，状态价值等信息以供后续使用 """
        if self.actor_critic.is_recurrent:
            self.transition.hidden_states = self.actor_critic.get_hidden_states()
        # Compute the actions and values
        self.transition.actions = self.actor_critic.act(obs)
        self.transition.actions = self.transition.actions.detach()
        self.transition.values = self.actor_critic.evaluate(critic_obs).detach()
        self.transition.actions_log_prob = self.actor_critic.get_actions_log_prob(self.transition.actions).detach()
        self.transition.action_mean = self.actor_critic.action_mean.detach()
        self.transition.action_sigma = self.actor_critic.action_std.detach()
        # need to record obs and critic_obs before env.step()
        self.transition.observations = obs
        self.transition.critic_observations = critic_obs
        return self.transition.actions
